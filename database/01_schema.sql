-- SSMS schema (Indus Security Services). Run this first, then 02_seed_data.sql
CREATE DATABASE IF NOT EXISTS ssms;
USE ssms;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS USERS, INVOICE, PAYROLL, EQUIPMENT, ATTENDANCE, GUARD_DEPLOYMENT,
  SECURITY_SITE, CLIENT, GUARD, EMPLOYEE, BRANCH;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE BRANCH (
  BranchID INT AUTO_INCREMENT PRIMARY KEY,
  BranchName VARCHAR(100) NOT NULL,
  City VARCHAR(50), Address VARCHAR(255), ContactNumber VARCHAR(20)
) ENGINE=InnoDB;

CREATE TABLE EMPLOYEE (
  EmployeeID INT AUTO_INCREMENT PRIMARY KEY,
  FullName VARCHAR(100) NOT NULL,
  CNIC VARCHAR(15) UNIQUE,
  PhoneNumber VARCHAR(20), Address VARCHAR(255),
  BranchID INT,
  Role ENUM('Guard','Supervisor','Operations Manager','General Manager','Accountant') NOT NULL,
  HireDate DATE,
  FOREIGN KEY (BranchID) REFERENCES BRANCH(BranchID)
) ENGINE=InnoDB;

-- FullName removed from GUARD: it already lives in EMPLOYEE (3NF)
CREATE TABLE GUARD (
  EmployeeID INT PRIMARY KEY,
  Availability VARCHAR(20), Status VARCHAR(20),
  FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID)
) ENGINE=InnoDB;

CREATE TABLE CLIENT (
  ClientID INT AUTO_INCREMENT PRIMARY KEY,
  CompanyName VARCHAR(150) NOT NULL, ContactPerson VARCHAR(100),
  ContactNumber VARCHAR(20), Email VARCHAR(100), OfficeAddress VARCHAR(255),
  ContractStartDate DATE, ContractEndDate DATE
) ENGINE=InnoDB;

CREATE TABLE SECURITY_SITE (
  SiteID INT AUTO_INCREMENT PRIMARY KEY,
  ClientID INT, SiteName VARCHAR(100) NOT NULL, City VARCHAR(50),
  ContactNumber VARCHAR(20), SupervisorID INT,
  FOREIGN KEY (ClientID) REFERENCES CLIENT(ClientID),
  FOREIGN KEY (SupervisorID) REFERENCES EMPLOYEE(EmployeeID)
) ENGINE=InnoDB;

CREATE TABLE GUARD_DEPLOYMENT (
  DeploymentID INT AUTO_INCREMENT PRIMARY KEY,
  GuardID INT NOT NULL, SiteID INT NOT NULL,
  Shift ENUM('Day','Night') NOT NULL,
  StartDate DATE, EndDate DATE NULL,
  FOREIGN KEY (GuardID) REFERENCES GUARD(EmployeeID),
  FOREIGN KEY (SiteID) REFERENCES SECURITY_SITE(SiteID)
) ENGINE=InnoDB;

CREATE TABLE ATTENDANCE (
  AttendanceID INT AUTO_INCREMENT PRIMARY KEY,
  EmployeeID INT, AttendanceDate DATE,
  CheckIn TIME NULL, CheckOut TIME NULL, AttendanceStatus VARCHAR(20),
  FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID),
  INDEX idx_att_date (AttendanceDate)
) ENGINE=InnoDB;

CREATE TABLE PAYROLL (
  PayrollID INT AUTO_INCREMENT PRIMARY KEY,
  EmployeeID INT, BaseSalary DECIMAL(10,2), Allowances DECIMAL(10,2),
  NetSalary DECIMAL(10,2), PaymentMethod VARCHAR(30), PaymentStatus VARCHAR(20),
  FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID)
) ENGINE=InnoDB;

CREATE TABLE EQUIPMENT (
  EquipmentID INT AUTO_INCREMENT PRIMARY KEY,
  EquipmentName VARCHAR(60) NOT NULL, SerialNo VARCHAR(30) UNIQUE,
  Status VARCHAR(20), AssignedTo INT NULL,
  FOREIGN KEY (AssignedTo) REFERENCES EMPLOYEE(EmployeeID)
) ENGINE=InnoDB;

CREATE TABLE INVOICE (
  InvoiceID INT AUTO_INCREMENT PRIMARY KEY,
  ClientID INT NOT NULL, InvoiceDate DATE, DueDate DATE,
  Amount DECIMAL(12,2), Status VARCHAR(20),
  FOREIGN KEY (ClientID) REFERENCES CLIENT(ClientID)
) ENGINE=InnoDB;

-- Dashboard logins (GM, Operations Manager, Accountant). Demo-grade SHA2 hashing.
CREATE TABLE USERS (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  EmployeeID INT NOT NULL, Username VARCHAR(30) UNIQUE NOT NULL,
  PasswordHash CHAR(64) NOT NULL,
  FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID)
) ENGINE=InnoDB;
